-- ==========================================
-- 1. CREACIÓN DE DIMENSIONES
-- ==========================================

CREATE TABLE DimTiempo (
    Sk_Dim_Tiempo INT PRIMARY KEY, -- Formato AAAAMMDD (Ej: 20261030)
    FechaCompleta DATE NOT NULL,
    DiaSemana VARCHAR(20) NOT NULL,
    NumeroMes INT NOT NULL,
    Mes VARCHAR(20) NOT NULL,
    AnioMes VARCHAR(7) NOT NULL, -- Formato AAAA-MM
    Trimestre VARCHAR(2) NOT NULL, -- Ej: Q1, Q2
    Anio INT NOT NULL
);

CREATE TABLE DimProducto (
    Sk_Dim_Producto INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    CodigoProducto_NK VARCHAR(50) NOT NULL UNIQUE,
    NombreProducto VARCHAR(100) NOT NULL,
    Subcategoria VARCHAR(50) NOT NULL,
    Categoria VARCHAR(50) NOT NULL,
    Marca VARCHAR(50) NOT NULL
);

CREATE TABLE DimCliente (
    Sk_Dim_Cliente INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    IdCliente_NK VARCHAR(50) NOT NULL,
    NombreCompleto VARCHAR(100) NOT NULL,
    Genero VARCHAR(20) NOT NULL,
    Segmento VARCHAR(50) NOT NULL,
    FechaInicio DATE NOT NULL,
    FechaFin DATE NOT NULL,
    EsActual BOOLEAN NOT NULL,
    UNIQUE (IdCliente_NK, FechaInicio) -- Previene solapamientos
);

CREATE TABLE DimSucursal (
    Sk_Dim_Sucursal INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    CodigoSucursal_NK VARCHAR(50) NOT NULL UNIQUE,
    NombreSucursal VARCHAR(100) NOT NULL,
    Ciudad VARCHAR(50) NOT NULL,
    Region VARCHAR(50) NOT NULL,
    Pais VARCHAR(50) NOT NULL
);

CREATE TABLE DimCanal (
    Sk_Dim_Canal INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    CodigoCanal_NK VARCHAR(50) NOT NULL UNIQUE,
    TipoCanal VARCHAR(50) NOT NULL
);

CREATE TABLE DimPromocion (
    Sk_Dim_Promocion INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    CodigoPromocion_NK VARCHAR(50) NOT NULL UNIQUE,
    NombrePromocion VARCHAR(100) NOT NULL,
    TipoPromocion VARCHAR(50) NOT NULL
);

-- ==========================================
-- 2. CREACIÓN DE LA TABLA DE HECHOS
-- ==========================================

CREATE TABLE FactVentas (
    -- Claves Foráneas (No admiten nulos por regla de negocio)
    Sk_Dim_Tiempo INT NOT NULL,
    Sk_Dim_Cliente INT NOT NULL,
    Sk_Dim_Producto INT NOT NULL,
    Sk_Dim_Sucursal INT NOT NULL,
    Sk_Dim_Canal INT NOT NULL,
    Sk_Dim_Promocion INT NOT NULL,
    
    -- Dimensiones Degeneradas (Clave Primaria Compuesta)
    NumeroTransaccion VARCHAR(50) NOT NULL,
    NumeroLinea INT NOT NULL,
    
    -- Métricas Base
    CantidadVendida DECIMAL(10,2) NOT NULL CHECK (CantidadVendida > 0),
    MontoVenta DECIMAL(15,2) NOT NULL CHECK (MontoVenta >= 0),
    MontoDescuento DECIMAL(15,2) NOT NULL CHECK (MontoDescuento >= 0 AND MontoDescuento <= MontoVenta),
    CostoTotal DECIMAL(15,2) NOT NULL CHECK (CostoTotal >= 0),

    -- Restricciones y Relaciones
    PRIMARY KEY (NumeroTransaccion, NumeroLinea),
    FOREIGN KEY (Sk_Dim_Tiempo) REFERENCES DimTiempo(Sk_Dim_Tiempo),
    FOREIGN KEY (Sk_Dim_Cliente) REFERENCES DimCliente(Sk_Dim_Cliente),
    FOREIGN KEY (Sk_Dim_Producto) REFERENCES DimProducto(Sk_Dim_Producto),
    FOREIGN KEY (Sk_Dim_Sucursal) REFERENCES DimSucursal(Sk_Dim_Sucursal),
    FOREIGN KEY (Sk_Dim_Canal) REFERENCES DimCanal(Sk_Dim_Canal),
    FOREIGN KEY (Sk_Dim_Promocion) REFERENCES DimPromocion(Sk_Dim_Promocion)
);