"""Comprobaciones locales de semilla y DQL con SQLite; no sustituyen PostgreSQL."""

import re
import sqlite3
import unittest
from pathlib import Path


CARPETA = Path(__file__).resolve().parents[1] / "Equipo01_DataMart_Parcial01"
DDL = (CARPETA / "Equipo01_DataMart_DDL_Parcial01.sql").read_text(encoding="utf-8")
DML = (CARPETA / "Equipo01_DataMart_DML_Parcial01.sql").read_text(encoding="utf-8")
DQL = (CARPETA / "Equipo01_DataMart_DQL_Parcial01.sql").read_text(encoding="utf-8")


def consultar(db, id_consulta, parametros):
    patron = rf"-- BEGIN QUERY {id_consulta}\s+(.*?)-- END QUERY {id_consulta}"
    seccion = re.search(patron, DQL, re.DOTALL)
    if seccion is None:
        raise AssertionError(f"Falta la consulta {id_consulta}")
    sql = re.sub(r"^--.*$", "", seccion[1], flags=re.MULTILINE).replace("::date", "")
    return db.execute(sql, {str(indice): valor for indice, valor in enumerate(parametros, 1)}).fetchall()


class SemillaSQLTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.db = sqlite3.connect(":memory:")
        cls.db.execute("PRAGMA foreign_keys = ON")
        cls.db.create_function("translate", 3, lambda texto, origen, destino:
                               texto.translate(str.maketrans(origen, destino)))
        # SQLite no admite IDENTITY ni casts ::date; se sustituyen SOLO para esta
        # comprobación. Las consultas reales requieren una instancia PostgreSQL.
        cls.db.executescript(DDL.replace("GENERATED BY DEFAULT AS IDENTITY", ""))
        cls.db.executescript(DML)

    @classmethod
    def tearDownClass(cls):
        cls.db.close()

    def test_siete_preguntas_tienen_datos_para_demostracion(self):
        octubre = ("2025-10-01", "2025-10-31")
        self.assertEqual(len(consultar(self.db, "ranking_margen_categorias", (*octubre, 5))), 5)
        self.assertEqual(consultar(self.db, "ranking_margen_categorias", (*octubre, 5))[0][0], "Electrónica")
        self.assertEqual(consultar(self.db, "ranking_ticket_sucursales", octubre)[0][0], "Sucursal Caracas Principal")
        self.assertEqual(consultar(self.db, "ranking_valor_canales", octubre)[0][0], "Fisico")
        self.assertEqual(consultar(self.db, "lider_producto_categoria", (*octubre, "electronica"))[0][0], "Laptop Pro 15")
        self.assertEqual(consultar(self.db, "ingreso_neto_mensual", octubre)[0][0], "2025-10")
        caida = consultar(self.db, "mayor_caida_segmento",
                          (*octubre, "2025-11-01", "2025-11-30"))
        self.assertEqual(caida, [("Regular", 7, 1, 6)])
        canales = consultar(self.db, "comparacion_margen_canales", ("Fisico", "E-commerce"))
        self.assertEqual(len(canales), 6)
        self.assertEqual({fila[0] for fila in canales}, {"2026-08", "2026-09", "2026-10"})

    def test_periodo_sin_ventas_no_se_convierte_en_cero(self):
        self.assertEqual(consultar(self.db, "ranking_margen_categorias",
                                  ("2024-02-01", "2024-02-29", 5)), [])

    def test_sin_promocion_no_se_cuenta_como_desconocido(self):
        self.assertEqual(self.db.execute(
            "SELECT COUNT(*) FROM FactVentas WHERE Sk_Dim_Promocion = -1"
        ).fetchone()[0], 0)
        self.assertGreater(self.db.execute(
            "SELECT COUNT(*) FROM FactVentas WHERE Sk_Dim_Promocion = 0"
        ).fetchone()[0], 0)


if __name__ == "__main__":
    unittest.main()
